package org.gms.hotreload.versioned;

/**
 * 版本门判定结果。
 */
public enum VersionDecision {

    /** 写操作版本 == 当前逻辑版本：放行。 */
    ALLOW,

    /**
     * 写操作版本 &lt; 当前逻辑版本：迟到写（重载前已发起、重载后才落盘）。
     * 业务方按操作语义决定丢弃（状态快照类，旧逻辑产物已过时）或重放（幂等写类，
     * 操作在新逻辑下仍有效）。判定只负责"识别"，丢弃/重放是 M2 各写入口的业务策略。
     */
    STALE
}
