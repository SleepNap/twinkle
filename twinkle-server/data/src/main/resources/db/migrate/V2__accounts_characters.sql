-- ============================================================
-- 表结构对齐 newmaple 库（红线 2：MySQL newmaple 库兼容，表结构不改）
-- 与参考项目 characters 结构一致（红线 3：~60 列存档格式不变）。
-- 方言节：-- dialect:sqlite / -- dialect:postgresql / -- dialect:mysql
-- 注意：节内语句之间【不要用空行】——MigrationRunner.filterForDialect 约定
-- "空行 = 节结束回全方言"，节内空行会导致后续语句泄漏到所有方言（见
-- MigrationRunnerDialectFilterTest.blankLineResetsSectionToAllDialects）。
-- 思路参考自 BeiDou-Server（OdinMS 系），建表语句按 twinkle 三方言适配自研。
-- ============================================================

