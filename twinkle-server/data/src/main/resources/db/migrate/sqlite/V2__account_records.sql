-- ============================================================
CREATE TABLE IF NOT EXISTS account_records (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL DEFAULT '',
    password TEXT NOT NULL DEFAULT '',
    pin TEXT NOT NULL DEFAULT '',
    pic TEXT NOT NULL DEFAULT '',
    logged_in INTEGER NOT NULL DEFAULT 0,
    last_login TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    birthday TEXT NOT NULL DEFAULT '2005-05-11',
    banned INTEGER NOT NULL DEFAULT 0,
    ban_reason TEXT,
    mac_addresses TEXT,
    nx_credit INTEGER,
    maple_point INTEGER,
    nx_prepaid INTEGER,
    character_slots INTEGER NOT NULL DEFAULT 3,
    gender INTEGER NOT NULL DEFAULT 10,
    temp_ban TEXT NOT NULL DEFAULT '2005-05-11 00:00:00',
    greason INTEGER NOT NULL DEFAULT 0,
    tos INTEGER NOT NULL DEFAULT 0,
    site_logged TEXT,
    web_admin INTEGER DEFAULT 0,
    nick TEXT,
    mute INTEGER DEFAULT 0,
    email TEXT,
    ip TEXT,
    reward_points INTEGER NOT NULL DEFAULT 0,
    vote_points INTEGER NOT NULL DEFAULT 0,
    hwid TEXT NOT NULL DEFAULT '',
    language INTEGER NOT NULL DEFAULT 3
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_account_records_name ON account_records(name);
CREATE INDEX IF NOT EXISTS idx_account_records_id_banned ON account_records(id, banned);

